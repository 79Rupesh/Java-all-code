public class A20 {
    public static void main(String[] args) {
        int recharge = 599;
        if (recharge == 199) {
            int prati_day = 1 * 28;
            System.out.println("199 ka 28 ka data : " + prati_day);
        } else if (recharge == 399) {
            int prati_day = 2 * 28;
            System.out.println("399 ka 28 ka data : " + prati_day);
        } else if (recharge == 599) {
            int prati_day = 3 * 28;
            System.out.println("599 ka 28 ka data : " + prati_day);
        }
    }

}
