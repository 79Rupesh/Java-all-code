public class q8 {
    public static void main(String args[]) {
        int n = 26;
        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= n - i; j++) {
                System.out.print(" ");
            }
            for (int j = 0; j < i; j++) {
                System.out.print((char) ('A' + j));
            }

            // Decreasing letters
            for (int j = i - 2; j >= 0; j--) {
                System.out.print((char) ('A' + j));
            }

            System.out.println();
        }
        for (int i = 1; i <= 52; i++) {
            System.out.print("A");
        }

    }
}